"""Project agent context: one ``.ai/`` source, rendered for each assistant.

``.ai/`` is Archonix's convention, not an assistant standard. It holds:

* ``.ai/instructions.md``: project-wide agent instructions, rendered to ``AGENTS.md``
  (read by Codex, Cursor and Claude Code 2.1.277+) and a ``CLAUDE.md`` that imports it
  with ``@AGENTS.md`` (for Claude Code sessions that read only ``CLAUDE.md``);
* ``.ai/skills/<name>/``: project skills, copied to ``.claude/skills/`` (Claude Code)
  and ``.agents/skills/`` (Codex; Cursor reads it too).

``init`` drafts ``.ai/`` from static repository evidence and never overwrites files.
``sync`` renders the outputs, recording each file it writes, with its SHA-256, in
``.ai/.sync-manifest.json``. Like the skill installer, it never overwrites unmanaged or
hand-edited outputs, never writes through symlinks, and only removes files it wrote
itself whose content is unchanged. Both are dry runs unless ``apply=True``.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from . import __version__
from .config import Settings
from .errors import ArchonixError, PolicyError
from .install import _member, _sha256, _symlink_in_path, source_files, validate_skill
from .inventory import build_inventory
from .requirements import validate_ledger

AI_DIR = ".ai"
INSTRUCTIONS = "instructions.md"
SYNC_MANIFEST = ".sync-manifest.json"
GENERATED_MARK = (
    "<!-- Generated by `archonix agents sync` from .ai/instructions.md. "
    "Edit that file, not this one. -->"
)
CLAUDE_MD = (
    "<!-- Generated by `archonix agents sync`. Claude Code loads AGENTS.md through this "
    "import. -->\n@AGENTS.md\n"
)
SKILL_TARGETS = {"claude": ".claude/skills", "agents": ".agents/skills"}
DEFAULT_TARGETS = ("claude", "agents")


@dataclass
class Plan:
    actions: list[tuple[str, str]] = field(default_factory=list)  # (action, relative path)
    conflicts: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    applied: bool = False

    def as_dict(self) -> dict[str, Any]:
        return {
            "applied": self.applied,
            "conflicts": self.conflicts,
            "notes": self.notes,
            "actions": [{"action": a, "path": p} for a, p in self.actions],
        }


def slug(name: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return (value or "project")[:40].strip("-")


# ---------------------------------------------------------------------------- init


def _package_scripts(root: Path) -> dict[str, str]:
    path = root / "package.json"
    if not path.is_file() or path.is_symlink() or path.stat().st_size > 1_000_000:
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    scripts = data.get("scripts") if isinstance(data, dict) else None
    if not isinstance(scripts, dict):
        return {}
    return {k: v for k, v in scripts.items() if isinstance(k, str) and isinstance(v, str)}


def _load_ledger(root: Path) -> dict[str, Any] | None:
    path = root / "docs" / "requirements.json"
    if not path.is_file() or path.is_symlink():
        return None
    try:
        ledger = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return ledger if validate_ledger(ledger).ok else None


def _commands(inv: dict[str, Any], scripts: dict[str, str]) -> list[str]:
    names = {(d["category"], d["name"]) for d in inv["detections"]}
    lines = []
    if ("test", "pytest") in names:
        lines.append(
            "- Tests (Python): `pytest`; with Archonix evidence: "
            "`archonix check run . --mode audit --allow-repo-code --checks pytest`"
        )
    for script in ("test", "lint", "typecheck", "build"):
        if script in scripts:
            lines.append(f"- `npm run {script}` (package.json: `{scripts[script]}`)")
    if ("lint", "Ruff") in names:
        lines.append("- Lint (Python): `ruff check .`")
    if ("typecheck", "mypy") in names:
        lines.append("- Types (Python): `mypy`")
    if not lines:
        lines.append("- TODO: no test, lint or build commands were detected; add them here.")
    lines.append(
        "- Static security and quality checks: `archonix check plan . --mode audit`, "
        "then `archonix check run . --mode audit --checks <ids>`"
    )
    return lines


def render_instructions(root: Path, settings: Settings) -> str:
    """Draft ``.ai/instructions.md`` from static evidence; unknowns are marked TODO."""
    inv = build_inventory(root, settings)
    scripts = _package_scripts(root)
    ledger = _load_ledger(root)
    name = ledger["project"] if ledger else root.name
    today = datetime.now(UTC).date().isoformat()
    out = [
        f"# {name}: instructions for AI coding agents",
        "",
        f"<!-- Drafted by `archonix agents init` on {today} from repository evidence. Review "
        "and edit; then run `archonix agents sync` to update AGENTS.md and CLAUDE.md. -->",
        "",
        "## Project",
        "",
    ]
    docs = [
        p
        for p in (
            "docs/product-spec.md",
            "docs/business-rules.md",
            "docs/architecture.md",
            "docs/technology-stack.md",
        )
        if (root / p).is_file()
    ]
    if docs:
        out.append(
            "Read these before changing behaviour: " + ", ".join(f"`{p}`" for p in docs) + "."
        )
    else:
        out.append("TODO: one paragraph on what this product does and for whom.")
    out += ["", "## Stack (detected from files; verify)", ""]
    shown = [
        d
        for d in inv["detections"]
        if d["category"]
        in {
            "framework",
            "language",
            "database",
            "cache",
            "queue",
            "auth",
            "test",
            "lint",
            "typecheck",
            "package-manager",
            "container",
            "ci",
            "api-spec",
            "monorepo",
        }
    ]
    for d in shown[:25]:
        status = "seen in config" if d["basis"] != "declared-dependency" else "declared dependency"
        out.append(f"- {d['category']}: {d['name']} ({status}; {d['evidence'][0]})")
    if not shown:
        out.append("- TODO: no stack detected from manifests or configuration.")
    out += ["", "## Repository layout", ""]
    for p in inv["projects"]:
        out.append(f"- `{p['path']}`: {', '.join(p['ecosystems'])} ({', '.join(p['manifests'])})")
    if not inv["projects"]:
        out.append("- TODO: describe the main directories.")
    out += ["", "## Build, test and check", "", *_commands(inv, scripts), ""]
    out += ["## Requirements", ""]
    if ledger:
        musts = [r for r in ledger["requirements"] if r["priority"] == "must"]
        out.append(
            f"The ledger `docs/requirements.json` has {len(ledger['requirements'])} "
            f"requirement(s). Map every change to a requirement or acceptance criterion "
            "ID and update its status and evidence."
        )
        out.append("")
        if musts:
            out += ["Must-have requirements (priority `must`; full details in the ledger):", ""]
        else:
            out.append("The ledger has no must-have requirements yet.")
        out += [f"- {r['id']} ({r['status']}): {r['title']}" for r in musts[:20]]
        if len(musts) > 20:
            out.append(f"- … and {len(musts) - 20} more must-have requirements")
    else:
        out.append(
            "No requirements ledger yet. For new features, run the Archonix discovery "
            "workflow first (`archonix docs init . --set discovery`)."
        )
    out += [
        "",
        "## Working rules",
        "",
        "- Use the Archonix skill workflows (repository understanding, implementation, bug "
        "investigation, testing, security, release readiness) when they are installed.",
        "- Make small changes mapped to requirement IDs, and inspect the diff before reporting.",
        "- Run the relevant tests. If they cannot be run, report them as **not run** with the "
        "exact command. Never weaken tests, validation or authorization to make checks pass.",
        "- Never commit secrets; use synthetic values in tests and fixtures.",
        "",
        "## Conventions",
        "",
        "- TODO: naming, error handling, logging and API conventions (not inferable from files).",
        "",
    ]
    return "\n".join(out)


def _yaml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_domain_skill(ledger: dict[str, Any], skill_name: str, has_rules: bool) -> str:
    """A project skill carrying requirements and acceptance criteria, loaded on demand."""
    project = re.sub(r"\s+", " ", ledger["project"]).strip()
    description = (
        f"Requirements and acceptance criteria of {project}. Use when implementing, testing or "
        "reviewing a change to this project's behaviour, to find the requirement and "
        "acceptance criterion IDs it must satisfy."
    )
    out = [
        "---",
        f"name: {skill_name}",
        f"description: {_yaml_string(description)}",
        "---",
        "",
        f"# {project}: requirements",
        "",
        "Generated by `archonix agents init` from `docs/requirements.json`; the ledger is "
        "authoritative. Re-run init (or edit this file) when requirements change.",
        "",
    ]
    for r in ledger["requirements"]:
        if r["status"] in {"rejected"}:
            continue
        out += [
            f"## {r['id']}: {r['title']} ({r['priority']}, {r['status']})",
            "",
            r["description"],
            "",
        ]
        out += [f"- {ac['id']}: {ac['description']}" for ac in r["acceptance_criteria"]]
        open_q = [
            q
            for q in r.get("open_questions", [])
            if not q.get("resolution") and not q.get("accepted_as_assumption")
        ]
        out += [f"- Open question {q['id']}: {q['question']}" for q in open_q]
        out.append("")
    if has_rules:
        out.append("Business rules are documented in `docs/business-rules.md`.")
    return "\n".join(out).rstrip() + "\n"


def init(root: Path, settings: Settings, *, allow_source_writes: bool, apply: bool) -> Plan:
    root = root.resolve()
    plan = Plan()
    ai = root / AI_DIR
    if _symlink_in_path(root, ai / INSTRUCTIONS) is not None:
        plan.conflicts.append(f"{AI_DIR} is or contains a symlink; refusing to write")
        return plan
    files: dict[str, str] = {INSTRUCTIONS: render_instructions(root, settings)}
    ledger = _load_ledger(root)
    if ledger:
        name = f"{slug(ledger['project'])}-requirements"
        files[f"skills/{name}/SKILL.md"] = render_domain_skill(
            ledger, name, (root / "docs" / "business-rules.md").is_file()
        )
    else:
        plan.notes.append(
            "no valid docs/requirements.json; the requirements skill was not generated"
        )
    for rel, _ in files.items():
        plan.actions.append(("exists" if (ai / rel).exists() else "create", f"{AI_DIR}/{rel}"))
    if not apply:
        return plan
    if not allow_source_writes:
        raise PolicyError(
            "writing .ai/ into the repository is a source modification; "
            "re-run with --allow-source-writes"
        )
    for rel, text in files.items():
        dest = _member(root, f"{AI_DIR}/{rel}")
        if dest is None:
            raise PolicyError(f"{AI_DIR}/{rel}: path is unsafe (symlink); stopped")
        if dest.exists():
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if _member(root, f"{AI_DIR}/{rel}") is None:
            raise PolicyError(f"{AI_DIR}/{rel}: path became unsafe; stopped")
        dest.write_text(text, encoding="utf-8")
    plan.applied = True
    return plan


# ---------------------------------------------------------------------------- sync


def _desired_outputs(
    root: Path, targets: tuple[str, ...]
) -> tuple[dict[str, bytes], str | None, list[str]]:
    """Return (outputs, blocking problem or None, notes about skipped skills)."""
    ai = root / AI_DIR
    problems: list[str] = []
    outputs: dict[str, bytes] = {}
    instructions = ai / INSTRUCTIONS
    if not instructions.is_file() or instructions.is_symlink():
        return {}, f"{AI_DIR}/{INSTRUCTIONS} not found (run `archonix agents init`)", []
    body = instructions.read_text(encoding="utf-8")
    outputs["AGENTS.md"] = f"{GENERATED_MARK}\n\n{body.rstrip()}\n".encode()
    if "claude" in targets:
        outputs["CLAUDE.md"] = CLAUDE_MD.encode()
    skills_dir = ai / "skills"
    if skills_dir.is_dir() and not skills_dir.is_symlink():
        for skill in sorted(p for p in skills_dir.iterdir() if p.is_dir()):
            if skill.is_symlink():
                problems.append(f"{AI_DIR}/skills/{skill.name} is a symlink; skipped")
                continue
            issues = [i for i in validate_skill(skill) if "(informational)" not in i]
            if issues:
                problems.append(f"{AI_DIR}/skills/{skill.name}: " + "; ".join(issues))
                continue
            for rel, src in source_files(skill).items():
                for target in targets:
                    outputs[f"{SKILL_TARGETS[target]}/{skill.name}/{rel}"] = src.read_bytes()
    return outputs, None, problems


def _read_sync_manifest(root: Path) -> dict[str, str]:
    path = root / AI_DIR / SYNC_MANIFEST
    if not path.is_file() or path.is_symlink():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ArchonixError(f"{path} is corrupt; inspect it manually") from exc
    files = data.get("files") if isinstance(data, dict) else None
    if not isinstance(files, dict):
        raise ArchonixError(f"{path} is not an Archonix sync manifest")
    return {k: v for k, v in files.items() if isinstance(k, str) and isinstance(v, str)}


def sync(
    root: Path,
    *,
    targets: tuple[str, ...] = DEFAULT_TARGETS,
    allow_source_writes: bool = False,
    apply: bool = False,
) -> Plan:
    root = root.resolve()
    unknown = [t for t in targets if t not in SKILL_TARGETS]
    if unknown:
        raise ArchonixError(
            f"unknown target(s) {', '.join(unknown)}; choose from {', '.join(SKILL_TARGETS)}"
        )
    plan = Plan()
    desired, blocking, notes = _desired_outputs(root, targets)
    if blocking:
        plan.conflicts.append(blocking)
    plan.notes += notes
    old = _read_sync_manifest(root)
    unsafe = [rel for rel in {*desired, *old} if _member(root, rel) is None]
    plan.conflicts += [
        f"{rel}: path is unsafe (absolute, '..' or through a symlink)" for rel in sorted(unsafe)
    ]
    if plan.conflicts:
        return plan
    for rel, content in sorted(desired.items()):
        dest = root / rel
        if not dest.exists():
            plan.actions.append(("create", rel))
        elif rel not in old:
            if rel == "CLAUDE.md":
                plan.notes.append(
                    "CLAUDE.md exists and is not managed by Archonix; left "
                    "unchanged. Add a line `@AGENTS.md` to it so Claude Code "
                    "loads the shared instructions."
                )
                continue
            plan.conflicts.append(
                f"{rel}: exists but is not managed by Archonix; merge it into .ai/ or move it aside"
            )
        elif _sha256(dest) != old[rel]:
            plan.conflicts.append(
                f"{rel}: edited by hand since the last sync; edit the .ai/ "
                "source instead, or move your changes there"
            )
        elif dest.read_bytes() == content:
            plan.actions.append(("unchanged", rel))
        else:
            plan.actions.append(("update", rel))
    for rel, digest in sorted(old.items()):
        if rel not in desired:
            dest = root / rel
            if dest.is_file() and _sha256(dest) == digest:
                plan.actions.append(("remove-stale", rel))
            elif dest.exists():
                plan.conflicts.append(f"{rel}: no longer generated but edited by hand; left")
    if plan.conflicts or not apply:
        return plan
    if not allow_source_writes:
        raise PolicyError(
            "writing AGENTS.md and skills into the repository is a source "
            "modification; re-run with --allow-source-writes"
        )
    written: dict[str, str] = {rel: digest for rel, digest in old.items() if rel in desired}
    for action, rel in plan.actions:
        target = _member(root, rel)
        if target is None:
            raise PolicyError(f"{rel}: path became unsafe during sync; stopped")
        dest = target
        if action in {"create", "update"}:
            dest.parent.mkdir(parents=True, exist_ok=True)
            if _member(root, rel) is None:
                raise PolicyError(f"{rel}: path became unsafe during sync; stopped")
            dest.write_bytes(desired[rel])
            written[rel] = _sha256(dest)
        elif action == "unchanged":
            written[rel] = _sha256(dest)
        elif action == "remove-stale":
            dest.unlink()
    manifest = root / AI_DIR / SYNC_MANIFEST
    manifest.write_text(
        json.dumps(
            {"tool": "archonix", "version": __version__, "files": dict(sorted(written.items()))},
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    plan.applied = True
    return plan


def out_of_date(plan: Plan) -> bool:
    """For `--check`: true when a sync would change anything or cannot proceed."""
    return bool(plan.conflicts) or any(a != "unchanged" for a, _ in plan.actions)
