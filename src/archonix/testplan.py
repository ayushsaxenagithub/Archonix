"""Generate one test stub per acceptance criterion (``archonix tests scaffold``).

Stubs follow the naming convention in :mod:`archonix.testcases`, so their results link
back to acceptance criteria in the traceability matrix without editing the ledger.

Stubs are *pending* by default (``pytest.skip`` / ``test.skip``): they are reported as
skipped, which traceability treats as unknown, never as passed. ``failing=True`` makes
them fail until implemented, for test-first work. ``test.todo`` is deliberately not used
because jest-junit reports it like a passing test.

Existing files are never overwritten; writing into the repository needs
``allow_source_writes``. One file is generated per requirement.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .errors import ArchonixError, PolicyError
from .install import _member
from .requirements import validate_ledger
from .testcases import encode_ac

FRAMEWORKS = ("pytest", "jest", "vitest")
SKIPPED_STATUSES = {"rejected", "deferred"}


@dataclass
class ScaffoldPlan:
    files: list[tuple[str, str, int]] = field(default_factory=list)  # (action, path, n stubs)
    notes: list[str] = field(default_factory=list)
    written: bool = False

    def as_dict(self) -> dict[str, Any]:
        return {
            "written": self.written,
            "notes": self.notes,
            "files": [{"action": a, "path": p, "stubs": n} for a, p, n in self.files],
        }


def _words(text: str, limit: int = 40) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    if len(slug) > limit:
        cut = slug[: limit + 1]
        slug = cut[: cut.rfind("_")] if "_" in cut else slug[:limit]
    return slug.strip("_") or "criterion"


def _quoted(text: str) -> str:
    """A string literal valid in both Python and JavaScript (JSON escaping)."""
    return json.dumps(text, ensure_ascii=False)


def render_pytest(req: dict[str, Any], failing: bool) -> str:
    lines = [
        f'"""Acceptance tests for {req["id"]}: {req["title"]}.',
        "",
        "Generated by `archonix tests scaffold`. Each test name carries its acceptance",
        "criterion ID (test_<id>__...) so results link back to docs/requirements.json.",
        'Replace each stub body with a real test; keep the name prefix."""',
        "",
        "import pytest",
        "",
    ]
    for ac in req["acceptance_criteria"]:
        name = f"test_{encode_ac(ac['id'])}__{_words(ac['description'])}"
        message = _quoted(f"not implemented: {ac['id']}")
        lines += [
            "",
            f"def {name}() -> None:",
            f"    {_quoted(ac['id'] + ': ' + ac['description'])}",
            f"    pytest.{'fail' if failing else 'skip'}({message})",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def render_js(req: dict[str, Any], framework: str, failing: bool) -> str:
    header = [
        f"// Acceptance tests for {req['id']}: {req['title']}.",
        "// Generated by `archonix tests scaffold`. Each test title starts with its acceptance",
        "// criterion ID so results link back to docs/requirements.json. Replace each stub with",
        "// a real test and keep the ID prefix. (test.todo is not used: jest-junit reports it",
        "// like a passing test.)",
    ]
    if framework == "vitest":
        header.append('import { describe, test } from "vitest";')
    body = [f"describe({_quoted(req['id'] + ': ' + req['title'])}, () => {{"]
    for ac in req["acceptance_criteria"]:
        title = _quoted(f"{ac['id']}: {ac['description']}")
        if failing:
            body.append(f"  test({title}, () => {{")
            body.append(f"    throw new Error({_quoted('not implemented: ' + ac['id'])});")
            body.append("  });")
        else:
            body.append(f"  test.skip({title}, () => {{}});")
    body.append("});")
    return "\n".join([*header, "", *body]) + "\n"


def _file_name(req_id: str, framework: str, typescript: bool) -> str:
    if framework == "pytest":
        return f"test_{encode_ac(req_id)}.py"
    return f"{req_id.lower()}.test.{'ts' if typescript else 'js'}"


def scaffold(
    root: Path,
    *,
    framework: str,
    ledger_path: Path | None = None,
    out_dir: str | None = None,
    typescript: bool = False,
    failing: bool = False,
    allow_source_writes: bool = False,
    apply: bool = False,
) -> ScaffoldPlan:
    if framework not in FRAMEWORKS:
        raise ArchonixError(f"unknown framework {framework!r}; choose from {', '.join(FRAMEWORKS)}")
    root = root.resolve()
    ledger_file = ledger_path or root / "docs" / "requirements.json"
    try:
        ledger = json.loads(ledger_file.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ArchonixError(f"{ledger_file}: requirements ledger not found") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise ArchonixError(f"{ledger_file}: cannot read ledger ({exc})") from exc
    result = validate_ledger(ledger)
    if not result.ok:
        raise ArchonixError("requirements ledger is invalid:\n  " + "\n  ".join(result.errors))
    directory = (out_dir or "tests/acceptance").strip("/")
    plan = ScaffoldPlan()
    outputs: dict[str, str] = {}
    for req in ledger["requirements"]:
        if req["status"] in SKIPPED_STATUSES:
            plan.notes.append(f"{req['id']}: status {req['status']}; no stubs generated")
            continue
        if not req["acceptance_criteria"]:
            plan.notes.append(f"{req['id']}: no acceptance criteria; nothing to scaffold")
            continue
        rel = f"{directory}/{_file_name(req['id'], framework, typescript)}"
        dest = _member(root, rel)
        if dest is None:
            raise PolicyError(f"{rel}: path is unsafe (absolute, '..' or through a symlink)")
        content = (
            render_pytest(req, failing)
            if framework == "pytest"
            else render_js(req, framework, failing)
        )
        count = len(req["acceptance_criteria"])
        plan.files.append(("exists" if dest.exists() else "create", rel, count))
        if not dest.exists():
            outputs[rel] = content
    if framework == "pytest" and outputs:
        plan.notes.append(
            "pytest discovers these files only if the directory is on its test "
            f"path; add `{directory}` to `testpaths` if you restrict it."
        )
    if not apply:
        return plan
    if not allow_source_writes:
        raise PolicyError(
            "writing test files into the repository is a source modification; "
            "re-run with --allow-source-writes"
        )
    for rel, content in outputs.items():
        dest = _member(root, rel)
        if dest is None:
            raise PolicyError(f"{rel}: path became unsafe; stopped")
        dest.parent.mkdir(parents=True, exist_ok=True)
        if _member(root, rel) is None:
            raise PolicyError(f"{rel}: path became unsafe; stopped")
        dest.write_text(content, encoding="utf-8")
    plan.written = True
    return plan
